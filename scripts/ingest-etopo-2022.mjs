import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  ETOPO_COLS,
  ETOPO_ROWS,
  ETOPO_STRIDE,
  buildEtopoOpendapUrl,
  encodeInt16Base64,
  parseEtopoAscii
} from "./etopo-utils.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const GENERATED_DIR = resolve(ROOT, "src/data/generated");
const OUTPUT_PATH = resolve(GENERATED_DIR, "etopo-2022.generated.js");
const MANIFEST_PATH = resolve(ROOT, "data/terrain-manifest.json");
const SOURCE_URL = buildEtopoOpendapUrl();
const SOURCE_DOI = "10.25921/fd45-gt74";
const METADATA_ID = "gov.noaa.ngdc.mgg.dem:etopo_2022";

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function round(value, digits = 6) {
  return Number(value.toFixed(digits));
}

function jsString(value) {
  return JSON.stringify(value);
}

function valueRange(values) {
  let minimum = Infinity;
  let maximum = -Infinity;
  for (const value of values) {
    if (value < minimum) minimum = value;
    if (value > maximum) maximum = value;
  }
  if (!Number.isFinite(minimum) || !Number.isFinite(maximum)) {
    throw new Error("ETOPO elevation grid did not contain finite values");
  }
  return { minimum, maximum };
}

const response = await fetch(SOURCE_URL, {
  headers: { "user-agent": "earth-777-etopo-ingest/1.0" }
});
if (!response.ok) {
  throw new Error(`Failed to fetch ETOPO 2022 OPeNDAP subset: ${response.status} ${response.statusText}`);
}
const rawText = await response.text();
const rawSha256 = sha256(rawText);
const expectedSha256 = process.env.ETOPO_EXPECTED_SHA256?.trim();
if (expectedSha256 && expectedSha256 !== rawSha256) {
  throw new Error(`ETOPO subset checksum changed: expected ${expectedSha256}, received ${rawSha256}`);
}

const parsed = parseEtopoAscii(rawText);
const base64 = encodeInt16Base64(parsed.elevations);
const { minimum: minimumElevation, maximum: maximumElevation } = valueRange(parsed.elevations);
const northLatitude = parsed.latitudes[0];
const southLatitude = parsed.latitudes.at(-1);
const westLongitude = parsed.longitudes[0];
const eastLongitude = parsed.longitudes.at(-1);
const latitudeStep = parsed.latitudes.length > 1 ? parsed.latitudes[0] - parsed.latitudes[1] : 0.5;
const longitudeStep = parsed.longitudes.length > 1 ? parsed.longitudes[1] - parsed.longitudes[0] : 0.5;

const meta = {
  id: "etopo-2022-bedrock-compact",
  source: "NOAA NCEI ETOPO 2022 Bedrock",
  sourceDoi: SOURCE_DOI,
  metadataId: METADATA_ID,
  sourceResolutionArcSeconds: 60,
  compactMethod: `centered index hyperslab; every ${ETOPO_STRIDE}th source cell in latitude and longitude`,
  rows: ETOPO_ROWS,
  cols: ETOPO_COLS,
  sampleSpacingDegrees: round(longitudeStep, 8),
  northLatitude: round(northLatitude, 8),
  southLatitude: round(southLatitude, 8),
  westLongitude: round(westLongitude, 8),
  eastLongitude: round(eastLongitude, 8),
  latitudeStepDegrees: round(latitudeStep, 8),
  longitudeStepDegrees: round(longitudeStep, 8),
  elevationUnits: "meters",
  horizontalCrs: "EPSG:4326",
  verticalDatum: "EGM2008 (EPSG:3855)",
  minimumElevationMeters: Math.round(minimumElevation),
  maximumElevationMeters: Math.round(maximumElevation),
  epistemicStatus: "study constrained modern bedrock baseline; compact grid is model-derived preprocessing and is not a direct reconstruction of 777 ka topography"
};

const moduleText = `// Generated by scripts/ingest-etopo-2022.mjs. Do not edit by hand.\n` +
`export const ETOPO_2022_META = Object.freeze(${JSON.stringify(meta, null, 2)});\n\n` +
`const ELEVATION_BASE64 = ${jsString(base64)};\n` +
`let elevationCache = null;\n\n` +
`function decodeElevations() {\n` +
`  if (elevationCache) return elevationCache;\n` +
`  const binary = atob(ELEVATION_BASE64);\n` +
`  const bytes = new Uint8Array(binary.length);\n` +
`  for (let index = 0; index < binary.length; index += 1) bytes[index] = binary.charCodeAt(index);\n` +
`  const view = new DataView(bytes.buffer);\n` +
`  const values = new Int16Array(bytes.byteLength / 2);\n` +
`  for (let index = 0; index < values.length; index += 1) values[index] = view.getInt16(index * 2, true);\n` +
`  elevationCache = values;\n` +
`  return elevationCache;\n` +
`}\n\n` +
`function wrapLongitude(longitude) {\n` +
`  return ((((Number(longitude) || 0) + 180) % 360) + 360) % 360 - 180;\n` +
`}\n\n` +
`export function bedrockElevationAt(latitude, longitude) {\n` +
`  const lat = Math.max(-90, Math.min(90, Number(latitude) || 0));\n` +
`  const lon = wrapLongitude(longitude);\n` +
`  const row = Math.max(0, Math.min(ETOPO_2022_META.rows - 1, Math.round((ETOPO_2022_META.northLatitude - lat) / ETOPO_2022_META.latitudeStepDegrees)));\n` +
`  const col = Math.max(0, Math.min(ETOPO_2022_META.cols - 1, Math.round((lon - ETOPO_2022_META.westLongitude) / ETOPO_2022_META.longitudeStepDegrees)));\n` +
`  return decodeElevations()[row * ETOPO_2022_META.cols + col];\n` +
`}\n\n` +
`export function isLandAt(latitude, longitude, seaLevelMeters = 0) {\n` +
`  return bedrockElevationAt(latitude, longitude) > (Number(seaLevelMeters) || 0);\n` +
`}\n`;

await mkdir(GENERATED_DIR, { recursive: true });
await writeFile(OUTPUT_PATH, moduleText);
const outputSha256 = sha256(moduleText);

const manifest = {
  schemaVersion: 1,
  generatedBy: "scripts/ingest-etopo-2022.mjs",
  retrieved: new Date().toISOString().slice(0, 10),
  source: {
    id: "etopo-2022-bedrock-60s",
    title: "ETOPO 2022 15 Arc-Second Global Relief Model — 60 arc-second Bedrock elevation distribution",
    datasetDoi: SOURCE_DOI,
    metadataId: METADATA_ID,
    access: "NCEI THREDDS OPeNDAP",
    opendapSubsetUrl: SOURCE_URL,
    rawSubsetSha256: rawSha256,
    sourceGrid: { rows: 10_800, cols: 21_600, resolutionArcSeconds: 60 },
    variables: {
      z: "Float32 height, meters, positive up",
      lat: "degrees_north",
      lon: "degrees_east"
    },
    transform: `Select centered every-${ETOPO_STRIDE}th latitude/longitude cell through a DAP2 hyperslab, yielding a ${ETOPO_ROWS} × ${ETOPO_COLS} half-degree global bedrock grid; round elevations to signed 16-bit integer meters and base64-encode for the browser.`
  },
  output: {
    file: "src/data/generated/etopo-2022.generated.js",
    sha256: outputSha256,
    rows: ETOPO_ROWS,
    cols: ETOPO_COLS,
    valueEncoding: "little-endian signed int16 meters, base64",
    minimumElevationMeters: Math.round(minimumElevation),
    maximumElevationMeters: Math.round(maximumElevation)
  },
  interpretation: {
    classification: "study constrained source; model-derived compact preprocessing",
    caveat: "ETOPO 2022 is a modern bedrock baseline, not a direct reconstruction of 777 ka topography. Earth 777 applies simulated paleo sea level separately and will add time-varying ice/isostasy/shoreline corrections in later phases."
  }
};
await writeFile(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);

console.log(`ETOPO compact grid: ${ETOPO_ROWS} × ${ETOPO_COLS}`);
console.log(`Source subset SHA-256: ${rawSha256}`);
console.log(`Elevation range: ${Math.round(minimumElevation)} to ${Math.round(maximumElevation)} m`);
console.log(`Generated: ${OUTPUT_PATH}`);
