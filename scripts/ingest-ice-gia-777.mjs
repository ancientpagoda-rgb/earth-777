import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { validateIceLoad777Grid } from "../src/reconstruction/SpatialIceLoad777.js";
import { validateGia777OutputCache } from "../src/reconstruction/GiaSolverOutputCache777.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT_PATH = resolve(ROOT, "src/data/generated/ice-gia-777.generated.js");
const MANIFEST_PATH = resolve(ROOT, "data/ice-gia-777-manifest.json");

function arg(name) {
  const prefix = `--${name}=`;
  const entry = process.argv.find((value) => value.startsWith(prefix));
  return entry ? entry.slice(prefix.length) : null;
}

const icePathArg = arg("ice");
const giaPathArg = arg("gia");
const runPathArg = arg("run");
if (!icePathArg || !giaPathArg || !runPathArg) {
  throw new Error("Usage: node scripts/ingest-ice-gia-777.mjs --ice=/path/ice.json --gia=/path/gia.json --run=/path/gia-run.json");
}

const icePath = resolve(icePathArg);
const giaPath = resolve(giaPathArg);
const runPath = resolve(runPathArg);
const [iceBytes, giaBytes, runBytes] = await Promise.all([readFile(icePath), readFile(giaPath), readFile(runPath)]);
const iceRaw = JSON.parse(iceBytes.toString("utf8"));
const giaRaw = JSON.parse(giaBytes.toString("utf8"));
const runRaw = JSON.parse(runBytes.toString("utf8"));
const iceRecords = Array.isArray(iceRaw) ? iceRaw : iceRaw.cells;
const giaRecords = Array.isArray(giaRaw) ? giaRaw : giaRaw.cells;
if (!Array.isArray(iceRecords) || !Array.isArray(giaRecords)) throw new Error("Ice and GIA JSON must be arrays or objects with a cells array.");

const iceGrid = validateIceLoad777Grid(iceRecords);
const giaCache = validateGia777OutputCache(giaRecords, runRaw);
if (iceGrid.rejectedCellCount > 0) {
  throw new Error(`Rejected ${iceGrid.rejectedCellCount} ice cells; every ingested thickness must be authorized as a direct or transformed 777 ka load.`);
}
if (!giaCache.run.validForTargetAssimilation) throw new Error("GIA run metadata is incomplete for 777 ka assimilation.");
if (giaCache.rejectedCellCount > 0) throw new Error(`Rejected ${giaCache.rejectedCellCount} GIA cells; every cell must contain finite U and N components.`);

const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");
const sourceHashes = Object.freeze({ ice: hash(iceBytes), gia: hash(giaBytes), run: hash(runBytes) });
const generatedIce = iceGrid.eligible.map((cell) => ({
  latitude: cell.latitude,
  longitude: cell.longitude,
  targetYearBP: cell.targetYearBP,
  iceThicknessMeters: cell.iceThicknessMeters,
  sigmaMeters: cell.sigmaMeters,
  cellAreaM2: cell.cellAreaM2,
  groundedFraction: cell.groundedFraction,
  directThicknessConstraint: cell.source.directThicknessConstraint,
  transformedToTargetIceLoad: cell.source.transformedToTargetIceLoad,
  modelId: cell.source.modelId,
  runId: cell.source.runId,
  sourceId: cell.source.sourceId,
  sourceDoi: cell.source.sourceDoi,
  configurationId: cell.source.configurationId,
  method: cell.source.method
}));
const generatedGia = giaCache.eligible.map((cell) => ({
  cellId: cell.cellId,
  latitude: cell.latitude,
  longitude: cell.longitude,
  globalEustaticMetersVsModern: cell.sample.globalEustaticMetersVsModern,
  globalEustaticSigmaMeters: cell.sample.globalEustaticSigmaMeters,
  solidEarthTargetMinusModernMeters: cell.sample.solidEarthTargetMinusModernMeters,
  solidEarthSigmaMeters: cell.sample.solidEarthSigmaMeters,
  localSeaSurfaceTargetMinusEustaticMeters: cell.sample.localSeaSurfaceTargetMinusEustaticMeters,
  localSeaSurfaceSigmaMeters: cell.sample.localSeaSurfaceSigmaMeters
}));
const meta = {
  schemaVersion: 1,
  targetYearBP: 777000,
  status: "ingested-external-model-output",
  iceRunId: generatedIce[0]?.runId ?? null,
  giaRunId: giaCache.run.runId,
  iceCellCount: generatedIce.length,
  giaCellCount: generatedGia.length,
  sourceHashes,
  epistemicRule: "These cells are explicit model/evidence products. Missing spatial coverage remains unknown and must not be interpreted as zero ice or zero GIA."
};
const moduleText = `// Generated by scripts/ingest-ice-gia-777.mjs. Do not edit by hand.\nexport const ICE_GIA_777_CACHE_META = Object.freeze(${JSON.stringify(meta, null, 2)});\n\nexport const ICE_LOAD_777_CELLS = Object.freeze(${JSON.stringify(generatedIce)}.map((cell) => Object.freeze(cell)));\n\nexport const GIA_777_OUTPUT_CELLS = Object.freeze(${JSON.stringify(generatedGia)}.map((cell) => Object.freeze(cell)));\n\nexport const GIA_777_RUN_METADATA = Object.freeze(${JSON.stringify(runRaw, null, 2)});\n`;
await writeFile(OUTPUT_PATH, moduleText);
const outputHash = hash(Buffer.from(moduleText));
await writeFile(MANIFEST_PATH, `${JSON.stringify({
  schemaVersion: 1,
  generatedBy: "scripts/ingest-ice-gia-777.mjs",
  targetYearBP: 777000,
  sources: { iceFile: icePathArg, giaFile: giaPathArg, runFile: runPathArg, sha256: sourceHashes },
  run: {
    solverId: giaCache.run.solverId,
    solverVersion: giaCache.run.solverVersion,
    solverSourceDoi: giaCache.run.solverSourceDoi,
    runId: giaCache.run.runId,
    iceHistoryId: giaCache.run.iceHistoryId,
    earthModelId: giaCache.run.earthModelId,
    rheologyDescription: giaCache.run.rheologyDescription,
    shorelineIteration: giaCache.run.shorelineIteration,
    rotationIncluded: giaCache.run.rotationIncluded,
    configurationHash: giaCache.run.configurationHash,
    inputManifestHash: giaCache.run.inputManifestHash,
    outputHash: giaCache.run.outputHash
  },
  validation: { iceEligibleCells: generatedIce.length, giaEligibleCells: generatedGia.length, giaRunStatus: giaCache.run.status },
  output: { file: "src/data/generated/ice-gia-777.generated.js", sha256: outputHash },
  caveat: "Ingestion validates provenance/schema eligibility; it does not independently validate the scientific correctness of the supplied ice history, rheology, solver configuration, or model fit."
}, null, 2)}\n`);
console.log(`Wrote ${generatedIce.length} ice-load cells and ${generatedGia.length} GIA cells for ${giaCache.run.runId}.`);
