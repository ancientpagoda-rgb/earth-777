import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const RAW_DIR = resolve(ROOT, "data/raw");
const GENERATED_DIR = resolve(ROOT, "src/data/generated");
const MANIFEST_PATH = resolve(ROOT, "data/manifest.json");
const OUTPUT_PATH = resolve(GENERATED_DIR, "paleo-forcing.generated.js");
const MAX_KA_BP = 777;
const RAD_TO_DEG = 180 / Math.PI;

const SOURCES = Object.freeze({
  orbital: {
    id: "la2004",
    file: "INSOLN.LA2004.BTL.ASC",
    url: "https://ssp.imcce.fr/insola/earth/online/earth/La2004/INSOLN.LA2004.BTL.ASC",
    sha256: "3f13b9f8e69085baf40bc67a2669e6f6af4148fef9218ed2158772aa91e35f8c"
  },
  seaLevel: {
    id: "spratt-lisiecki-2016",
    file: "spratt2016-noaa.txt",
    url: "https://www.ncei.noaa.gov/pub/data/paleo/contributions_by_author/spratt2016/spratt2016-noaa.txt",
    sha256: "02f56f02f709b70ac70fe5e403326272e19b42bf34ee9b1bba3b8322e1375dc1"
  }
});

const round = (value, digits) => Number(value.toFixed(digits));
const normalizeDegrees = (value) => ((value % 360) + 360) % 360;

async function sha256(path) {
  const bytes = await readFile(path);
  return createHash("sha256").update(bytes).digest("hex");
}

async function ensureSource(source) {
  const path = resolve(RAW_DIR, source.file);
  let bytes;
  try {
    bytes = await readFile(path);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    const response = await fetch(source.url);
    if (!response.ok) throw new Error(`Failed to fetch ${source.url}: ${response.status}`);
    bytes = Buffer.from(await response.arrayBuffer());
    await writeFile(path, bytes);
  }
  const digest = createHash("sha256").update(bytes).digest("hex");
  if (digest !== source.sha256) {
    throw new Error(`${source.file} checksum changed: expected ${source.sha256}, received ${digest}`);
  }
  return path;
}

function fortranNumber(token) {
  return Number(token.replace(/[dD]/, "E"));
}

async function parseOrbital(path) {
  const rows = [];
  for (const line of (await readFile(path, "utf8")).split(/\r?\n/)) {
    const fields = line.trim().split(/\s+/);
    if (fields.length !== 4) continue;
    const timeKa = fortranNumber(fields[0]);
    const kaBP = -timeKa;
    if (!Number.isInteger(kaBP) || kaBP < 0 || kaBP > MAX_KA_BP) continue;
    rows[kaBP] = [
      round(fortranNumber(fields[1]), 9),
      round(fortranNumber(fields[2]) * RAD_TO_DEG, 6),
      round(normalizeDegrees(fortranNumber(fields[3]) * RAD_TO_DEG), 6)
    ];
  }
  if (rows.length !== MAX_KA_BP + 1 || rows.some((row) => !row)) {
    throw new Error(`Expected ${MAX_KA_BP + 1} La2004 rows, received ${rows.filter(Boolean).length}`);
  }
  return rows;
}

async function parseSeaLevel(path) {
  const rows = [];
  for (const line of (await readFile(path, "utf8")).split(/\r?\n/)) {
    if (!/^\d/.test(line)) continue;
    const fields = line.split("\t");
    const kaBP = Number(fields[0]);
    if (!Number.isInteger(kaBP) || kaBP < 0 || kaBP > MAX_KA_BP) continue;
    const longStack = fields.slice(5, 9).map(Number);
    if (longStack.some((value) => !Number.isFinite(value))) {
      throw new Error(`Missing five-record sea-level stack at ${kaBP} ka BP`);
    }
    rows[kaBP] = longStack;
  }
  if (rows.length !== MAX_KA_BP + 1 || rows.some((row) => !row)) {
    throw new Error(`Expected ${MAX_KA_BP + 1} sea-level rows, received ${rows.filter(Boolean).length}`);
  }
  return rows;
}

await mkdir(RAW_DIR, { recursive: true });
await mkdir(GENERATED_DIR, { recursive: true });

const orbitalPath = await ensureSource(SOURCES.orbital);
const seaLevelPath = await ensureSource(SOURCES.seaLevel);
const orbital = await parseOrbital(orbitalPath);
const seaLevel = await parseSeaLevel(seaLevelPath);

